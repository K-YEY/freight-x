export function getTranslation(locale, key, params = {}) {
    const dict = translations[locale] || translations.ar;
    let text = dict[key] || translations.en[key] || key;
    
    Object.entries(params).forEach(([k, v]) => {
        text = text.replace(`{${k}}`, v);
    });
    
    return text;
}
